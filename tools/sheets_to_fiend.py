"""Turns Grok's front, side and back pictures of the Crimson Horned Fiend into voxel colour maps.
Each picture is scaled so the fiend is H voxels tall, then sampled into a grid; the game builds the body
from the three silhouettes and paints every face from the picture that sees it. Nothing is drawn by eye.
usage: python3 tools/sheets_to_fiend.py art-drop/monsters src/models/horned_fiend_data.js"""
import sys, json
import numpy as np
from PIL import Image
from scipy import ndimage as ndi

H = 80
XW = 34                       # model is XW voxels wide each way from the centre line
src, out = sys.argv[1], sys.argv[2]

def load(name):
    a = np.array(Image.open(f'{src}/fiend_{name}.jpg').convert('RGB')).astype(float)
    m = (a[:, :, 0] - a[:, :, 1]) > 18
    m = ndi.binary_fill_holes(ndi.binary_closing(ndi.binary_opening(m, iterations=1), iterations=2))
    lab, n = ndi.label(m); m = lab == (np.argmax(ndi.sum(m, lab, range(1, n + 1))) + 1)
    ys, xs = np.where(m)
    yb, yt = ys.max(), ys.min(); pxv = (yb - yt) / H
    rows = np.arange(int(yt + 0.45 * (yb - yt)), int(yt + 0.7 * (yb - yt)))   # chest rows: the centre line
    cx = np.mean([np.mean(np.where(m[r])[0]) for r in rows])
    return dict(a=a, m=m, yb=yb, pxv=pxv, cx=cx)

def sample(v, px, py):
    """colour of the picture block around (px, py), or None if the block is background"""
    h = v['pxv'] / 2
    x0, x1, y0, y1 = int(round(px - h)), int(round(px + h)), int(round(py - h)), int(round(py + h))
    if x0 < 0 or y0 < 0 or x1 > v['m'].shape[1] or y1 > v['m'].shape[0] or x1 <= x0 or y1 <= y0: return None
    if v['m'][y0:y1, x0:x1].mean() < 0.5: return None
    cx, cy = int(round(px)), int(round(py))
    blk = v['a'][cy - 1:cy + 2, cx - 1:cx + 2].reshape(-1, 3)
    gl = blk[(blk[:, 0] >= 232) & (blk[:, 1] >= 60) & (blk[:, 2] < 80)]
    return gl.mean(0) if len(gl) >= 2 else np.median(blk, axis=0)

F, B, S = load('front'), load('back'), load('side')
Z0, Z1 = -22, 44
cells = {}
def fill(tag, v, u_range, to_px):
    for y in range(H):
        for u in u_range:
            px = to_px(u); py = v['yb'] - (y + 0.5) * v['pxv']
            c = sample(v, px, py)
            if c is not None: cells[(tag, u, y)] = c
fill('f', F, range(-XW, XW), lambda x: F['cx'] - (x + 0.5) * F['pxv'])     # front picture: its right is -x
fill('b', B, range(-XW, XW), lambda x: B['cx'] + (x + 0.5) * B['pxv'])     # back picture: its right is +x
fill('s', S, range(Z0, Z1), lambda z: S['cx'] + (z + 0.5) * S['pxv'])      # side picture (seen from -x): its right is +z

def is_glow(c): return c[0] >= 232 and c[1] >= 60 and c[2] < 80
glow_keys = {k for k, c in cells.items() if is_glow(c)}
cols = np.array([c for k, c in cells.items() if k not in glow_keys])
rng = np.random.default_rng(5); K = 40
cent = cols[rng.choice(len(cols), K, replace=False)]
for _ in range(25):
    asg = ((cols[:, None, :] - cent[None]) ** 2).sum(2).argmin(1)
    for k in range(K):
        if (asg == k).any(): cent[k] = cols[asg == k].mean(0)
pal = [int(c[0]) << 16 | int(c[1]) << 8 | int(c[2]) for c in cent] + [0xff4500, 0xff9a1c]
CH = '0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ'
def pick(k):
    c = cells[k]
    if k in glow_keys: return CH[K + (1 if c[1] > 125 else 0)]
    return CH[int(((c - cent) ** 2).sum(1).argmin())]
def rows(tag, urange): return [''.join(pick((tag, u, y)) if (tag, u, y) in cells else '.' for u in urange) for y in range(H - 1, -1, -1)]
data = {'H': H, 'xw': XW, 'z0': Z0, 'z1': Z1, 'palette': pal, 'glow': [0] * K + [1, 1],
        'front': rows('f', range(-XW, XW)), 'back': rows('b', range(-XW, XW)), 'side': rows('s', range(Z0, Z1))}
open(out, 'w').write('/* Generated by tools/sheets_to_fiend.py from art-drop/monsters/fiend_{front,back,side}.jpg. Do not edit by hand.\n   Rows run top to bottom. front/back columns run -x to +x; side columns run -z (face) to +z (tail). "." is empty. */\n'
                     'const HornedFiendSheet = ' + json.dumps(data) + ';\nif (typeof module !== \'undefined\') module.exports = HornedFiendSheet;\n')
print('cells', len(cells), 'glow cells', len(glow_keys), 'views pxv', round(F['pxv'], 1), round(B['pxv'], 1), round(S['pxv'], 1), 'cx', round(F['cx']), round(B['cx']), round(S['cx']))
