"""Packs the effect sheets the look presets use (src/screen/fx_plan.js) into src/screen/fx_data.js, which the build adds to the page.
fx_data.js is git-ignored, like the raw art (see tools/extract_ct_assets.py): without it the game falls back to the plain voxel effects.
usage: python3 tools/pack_fx.py"""
import os, json, base64, subprocess
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(HERE, '..')
ct = os.path.join(ROOT, 'assets-private', 'ct')
meta = json.load(open(os.path.join(ct, 'fx_meta.json')))['efx']
need = json.loads(subprocess.check_output(['node', '-e', "console.log(JSON.stringify(require('./src/screen/fx_plan.js').needed()))"], cwd=ROOT))
sheets, size = {}, 0
for n in need:
    p = os.path.join(ct, 'misc', 'fx_' + n + '.png')
    if n not in meta or not os.path.exists(p): raise SystemExit('missing effect sheet: ' + n)
    raw = open(p, 'rb').read(); size += len(raw)
    m = meta[n]; sheets[n] = {'png': 'data:image/png;base64,' + base64.b64encode(raw).decode(), 'w': m['w'], 'h': m['h'], 'fr': m['fr']}
out = ('/* Generated by tools/pack_fx.py from the owner\'s free art packs (Super Pixel Effects by Will Tice / unTied Games, Tiny Swords by Pixel Frog). Do not edit; see docs/credits.md. */\n'
       'const FxData = ' + json.dumps(sheets, separators=(',', ':')) + ';\n')
open(os.path.join(ROOT, 'src', 'screen', 'fx_data.js'), 'w').write(out)
print('packed', len(sheets), 'sheets,', size // 1024, 'KB of images ->', len(out) // 1024, 'KB')
