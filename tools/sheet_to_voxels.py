"""Turns Grok's side-view picture of the rifle into voxel colour data, so the model carries every
panel, rune and glow cell the picture shows (no hand-placed approximations).
usage: python3 tools/sheet_to_voxels.py art-drop/gun/gun_side_master.jpg src/models/gothic_rifle_data.js
Mapping (same as gothic_rifle.js): 1 voxel = 1/S picture pixels, picture pixel (OX, OY) is gun space (z=0, y=0)."""
import sys, json
import numpy as np
from PIL import Image
from scipy import ndimage as ndi

RES = 2                      # voxels per sheet-voxel along each axis (2 keeps the thin glow lines and small panels)
S, OX, OY = 0.0885 * RES, 430, 395
src, out = sys.argv[1], sys.argv[2]
a = np.array(Image.open(src).convert('RGB')).astype(float)
lum = a.mean(2); red = a[:, :, 0] - a[:, :, 1]
mask = (red > 22) | (lum < 50)
mask = ndi.binary_fill_holes(ndi.binary_closing(ndi.binary_opening(mask, iterations=1), iterations=2))
lab, n = ndi.label(mask); mask = lab == (np.argmax(ndi.sum(mask, lab, range(1, n + 1))) + 1)
mask[:262, 340:625] = False          # the big scope on the sheet is replaced by the square-aperture sight (see gun sheet notes)

zmin, zmax = int(np.floor(-(1135 - OX) * S)), int(np.ceil(-(40 - OX) * S))
ymax, ymin = int(np.ceil((OY - 160) * S)), int(np.floor((OY - 610) * S))
cells, cols = {}, []
for z in range(zmin, zmax + 1):
    x0, x1 = OX - (z + 1) / S, OX - z / S
    for y in range(ymin, ymax + 1):
        p0, p1 = OY - (y + 1) / S, OY - y / S
        xa, xb, ya, yb = int(round(x0)), int(round(x1)), int(round(p0)), int(round(p1))
        if xb <= xa or yb <= ya or xa < 0 or ya < 0 or xb > a.shape[1] or yb > a.shape[0]: continue
        m = mask[ya:yb, xa:xb]
        if m.mean() < 0.5: continue
        # central part of the block only, so the dark grid lines between voxels do not dull the colour
        cx, cy = (xa + xb) // 2, (ya + yb) // 2
        blk = a[cy - 1:cy + 2, cx - 1:cx + 2].reshape(-1, 3)
        # glow lines are thin: if any pixel of the block is clearly glowing, the cell glows; otherwise take the median colour
        gl = blk[(blk[:, 0] >= 232) & (blk[:, 1] >= 60) & (blk[:, 2] < 80)]      # real glow is bright orange (r 245-255); lit crimson tops out near r 195
        cells[(z, y)] = gl.mean(0) if len(gl) >= 2 else np.median(blk, axis=0); cols.append(cells[(z, y)])
def is_glow(c): return c[0] >= 232 and c[1] >= 60 and c[2] < 80
glow_cells = {k: v for k, v in cells.items() if is_glow(v)}
cols = np.array([v for k, v in cells.items() if k not in glow_cells])
# cluster the lit-stone colours into a small palette so the model reads clean; glow cells get two fixed colours
rng = np.random.default_rng(3); K = 28
cent = cols[rng.choice(len(cols), K, replace=False)]
for _ in range(25):
    d = ((cols[:, None, :] - cent[None]) ** 2).sum(2); asg = d.argmin(1)
    for k in range(K):
        if (asg == k).any(): cent[k] = cols[asg == k].mean(0)
pal = [int(c[0]) << 16 | int(c[1]) << 8 | int(c[2]) for c in cent] + [0xff4d14, 0xff9a2a]
isglow = [0] * K + [1, 1]
CH = '0123456789abcdefghijklmnopqrstuvwxyz'
def pick(k, c):
    if k in glow_cells: return CH[K + (1 if c[1] > 125 else 0)]
    return CH[int(((c - cent) ** 2).sum(1).argmin())]
rows = []
for y in range(ymax, ymin - 1, -1):
    rows.append(''.join('.' if (z, y) not in cells else pick((z, y), cells[(z, y)]) for z in range(zmax, zmin - 1, -1)))
js = ('/* Generated by tools/sheet_to_voxels.py from art-drop/gun/gun_side_master.jpg. Do not edit by hand.\n'
      '   rows run top (high y) to bottom; columns run rear (high z) to muzzle (low z); "." is empty. */\n'
      'const GothicRifleSheet = ' + json.dumps({'palette': pal, 'glow': isglow, 'res': RES, 'zMax': zmax, 'zMin': zmin, 'yMax': ymax, 'yMin': ymin, 'rows': rows}) + ';\n'
      "if (typeof module !== 'undefined') module.exports = GothicRifleSheet;\n")
open(out, 'w').write(js)
print('cells', len(cells), 'palette', len(pal), 'glow entries', sum(isglow), 'z', zmin, zmax, 'y', ymin, ymax)
