"""Builds the Tiny Swords stone wall tile (32x64, seamless) from the cliff blocks in assets-private/ct and packs it into git-ignored src/screen/wall_data.js.
Without that file the game keeps its own painted stone. usage: python3 tools/pack_walls.py"""
import os, base64, io
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(HERE, '..')
src = Image.open(os.path.join(ROOT, 'assets-private', 'ct', 'TSO', 'g_Crypt.png')).convert('RGBA')
row = src.crop((320, 255, 512, 384))           # two rows of rounded cliff blocks
h = row.height // 2
tile = Image.new('RGBA', (32, 64))
for k in range(2):
    r = row.crop((0, k * h, 192, (k + 1) * h)).convert('RGB')
    r = r.crop((8 + 20 * k, 4, 8 + 20 * k + 32, h - 4)).resize((16, 32), Image.NEAREST)   # a 32px slice, halved: blocks come out chunky like ours
    r = r.resize((16, 32), Image.NEAREST)
    left = r; right = r.transpose(Image.FLIP_LEFT_RIGHT)     # mirror so the left and right edges meet
    tile.paste(left, (0, k * 32)); tile.paste(right, (16, k * 32))
buf = io.BytesIO(); tile.convert('RGB').save(buf, 'PNG')
out = ('/* Generated by tools/pack_walls.py from Tiny Swords by Pixel Frog (owner\'s free pack). Do not edit; see docs/credits.md. */\n'
       'const WallData = { stone: "data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode() + '" };\n')
open(os.path.join(ROOT, 'src', 'screen', 'wall_data.js'), 'w').write(out)
tile.resize((128, 256), Image.NEAREST).save(os.environ.get('WALL_PREVIEW', '/tmp/wall_preview.png'))
print('wall tile packed,', len(out) // 1024, 'KB')
